#!/usr/bin/env python3
"""Generate ``docs/coverage.md``: which Claude Code tools damage control judges, and how.

The README claim "what is covered" must not drift from the code, so the table is DERIVED from the
same tables the hooks use (``claude_code.MATCHERS``, ``adapter.HOOK_KINDS``, ``policy``): a tool
registered but not judged, or judged but not registered, shows up here.

    coverage_matrix.py          # write docs/coverage.md
    coverage_matrix.py --check  # exit 1 if it is stale
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import List

from damage_control import adapter, claude_code, engine, policy, scriptfile, toolcoverage

OUT = Path(__file__).resolve().parent.parent / "docs" / "coverage.md"

def render() -> str:
    path_kinds = set(policy._PATH_VERB)  # kinds that judge one path: block only, never ask
    rows: List[str] = []
    for matcher, hook in claude_code.MATCHERS.items():
        tools, shell = adapter.HOOK_KINDS[hook]
        if tools is None:
            kind, judges = "mcp", "the tool name and its path-valued arguments, plus, where a host profile maps the tool, the shell command it runs"
        else:
            names = [t for t, (_, _) in tools.items() if matcher == "mcp__.*" or t == matcher]
            kind = tools[names[0]][0] if names else "?"
            fields = tools[names[0]][1] if names else ()
            judges = "the command line" if kind == "shell" else f"the path in `{'` / `'.join(fields)}`"
            if kind in policy._SCRIPT_AUTHORING:
                judges += f", and script-looking text in `{adapter.CONTENT_FIELDS[matcher]}`"
        ask = "yes" if kind not in path_kinds or kind in policy._SCRIPT_AUTHORING else "no"
        rows.append(f"| `{matcher}` | `{hook}` | {judges} | yes | {ask} | yes |")
    return "\n".join([
        "# Coverage",
        "",
        "Which Claude Code tools damage control judges, and how. Anything not listed is not judged; see the",
        "[threat model](threat-model.md#what-it-does-not-protect-against).",
        "",
        "This page is generated by `tools/coverage_matrix.py` from the hooks' own tables; do not edit it by hand.",
        "CI fails if the committed file is stale. Regenerate with `python tools/coverage_matrix.py`.",
        "",
        "| Tool matcher | Hook | Judged on | Block | Ask | Audited |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "`Ask` is *no* for the read tools: a path is either allowed or blocked. An `ask` outside an attended",
        "session becomes a block (unattended) or an allow (bypass permission mode) -- except an `unverifiable`",
        "one, which bypass never demotes.",
        "",
        *decision_section(),
        *config_section(),
        *script_section(),
    ])


def decision_section() -> List[str]:
    """One decision per Claude Code tool, from ``toolcoverage.DECISIONS``."""
    rows = [f"| {', '.join(f'`{n}`' for n in d.names)} | {d.harm} | {d.decision} | {d.reason} |" for d in toolcoverage.DECISIONS]
    return [
        "## Decision per tool",
        "",
        "Every built-in tool name Claude Code is known to have, with whether it can do harm the judged tools cannot,",
        "and the decision. A tool listed *out of scope* has no hook registered, so nothing is judged for it.",
        "The names were read in Claude Code 2.1.319 from its binary and the hook-input schema it validates; the payload",
        "shapes of `Agent`, `Bash`, `Glob` and `Monitor` were also observed in a live session",
        "([hooks research](hooks-research.md#appendix-a-observed-payloads)). A test holds this table to the registered matchers; a tool Claude Code adds later is",
        "missing until someone reviews it and adds a row to `src/damage_control/toolcoverage.py`.",
        "",
        "| Tool | Can it do harm | Decision | Reason |",
        "|---|---|---|---|",
        *rows,
        "",
    ]


def config_section() -> List[str]:
    """The settings-change coverage, from the registration table the installer writes."""
    sources = ", ".join(f"`{s}`" for s in claude_code.CONFIG_SOURCES)
    return [
        "## Settings changes",
        "",
        f"One `{claude_code.CONFIG_EVENT}` hook (kind `{claude_code.CONFIG_KIND}`) judges a changed settings file, whatever wrote it;",
        f"see the [settings-change guard](config-change.md). Sources: {sources}. A change to a skill file is not judged.",
        "A block stops the change applying to the running session; a managed-policy change cannot be blocked and is audited as observed.",
        "",
    ]


def script_section() -> List[str]:
    """The script-indirection coverage, from the constants the scan itself uses."""
    shells = ", ".join(f"`{s}`" for s in sorted(engine._SCRIPT_SHELLS))
    interpreters = ", ".join(sorted({lang for _, lang in scriptfile._INTERPRETER_LANGS if lang != "shell"}))
    extensions = ", ".join(f"`{ext}`" for ext, lang in sorted(scriptfile._EXTENSION_LANGS.items()) if lang != "notebook")
    return [
        "## Script indirection",
        "",
        "A command that runs a file is judged on the file's text as well, by the same rules as a typed command.",
        "The file is read when the hook runs; see the [threat model](threat-model.md#script-indirection).",
        "",
        "| What | Covered |",
        "|---|---|",
        f"| Shells run on a file | {shells} (`sh x.sh`, `bash -e x.sh`), also through `sudo`, `env`, `nohup`, `time` and the other wrappers, and inside `sh -c '…'` |",
        "| Sourced files | `source x`, `. x` |",
        "| A path run directly | `./x`, `/abs/x`, `dir/x`, resolved against the payload cwd and each literal `cd` before it; the file's `#!` line picks the language, no `#!` means shell |",
        f"| Other interpreters on a file | {interpreters}: only the arguments of process-spawning and file-deleting calls are read, and a name bound once to a string literal is followed |",
        "| Write then run in one command | a body written with `>`, `>>`, `tee`, a heredoc, `echo` or `printf`, then run by path, is judged as written |",
        f"| Script text written with `Write`, `Edit` or `NotebookEdit` | a `#!` line, or an extension in {extensions}; a notebook code cell; the finding is an `ask` whatever the typed verdict is |",
        "| Task-runner recipes | `make` / `gmake` (Makefile, GNUmakefile, makefile; `-C`, `-f`, `NAME=value`; the named targets, their prerequisites and one level of `include`), "
        "`npm`, `pnpm`, `yarn` and `bun` (`run`, `test`, `start`, and `yarn` / `pnpm` script names: the `package.json` entry with its `pre` and `post` hooks), `just` (recipes, dependencies, parameters, `{{name}}` values, shebang recipes). "
        "The recipe text is judged as a shell script, and the verdict names the runner, the file and the rule |",
        "",
        "A recipe that cannot be resolved is an unverifiable `ask`, id `core.recipe-unverifiable`, never an allow: "
        "a variable or function the parser cannot evaluate, a conditional that decides a definition, a nested `include`, "
        "a workspace flag (`-w`, `--filter`, `-r`), a `just` recipe that may live in an imported file. "
        "A recipe that is not there is allowed, because running it fails.",
        "",
        "| Limit | Value | When exceeded |",
        "|---|---|---|",
        f"| File size | {scriptfile.MAX_SCRIPT_BYTES // 1024} KiB | unverifiable `ask`, id `core.script-too-large` |",
        f"| Scripts running scripts | {engine.MAX_SCRIPT_DEPTH} deep | unverifiable `ask`, id `core.script-depth` |",
        f"| Files read per command | {engine.MAX_SCRIPT_FILES}, {engine.MAX_SCRIPT_TOTAL_BYTES // 1024} KiB in all | unverifiable `ask`, id `core.script-budget` |",
        f"| Judging time per command | {engine.MAX_SCRIPT_SCAN_SECONDS} s | unverifiable `ask`, id `core.script-budget` |",
        "| A file that cannot be read | permission denied, a symlink loop | unverifiable `ask`, id `core.script-unreadable` |",
        "| A file this command names before running, and does not yet exist | `curl -o x.sh URL && sh x.sh` | unverifiable `ask`, id `core.script-unverifiable` |",
        "",
        "Inside a script, only what the rules positively recognize counts. A `# ask:` comment in a file is a",
        "comment, and a computed verb or a substitution is not asked about. The comment counts on the",
        "command that runs the script.",
        "",
        "**Not covered:** scripts fetched at run time (`curl URL | sh` is its own rule, id `core.fetched-program-pipe`);",
        "`task` (Taskfile) recipes, which need a YAML parser, and what `make` or `just` evaluate while reading the file (`$(shell …)`, backticks); "
        "other recipes run by a tool (`pip install` hooks, `cargo build` scripts, `npm install` lifecycle hooks); binaries;",
        "interpreters reading their program from stdin; a file that changes between the hook's read and the run;",
        "obfuscated or computed commands in a script; paths held in variables (`bash \"$S\"`); scripts run by `find -exec`",
        "or `xargs`; PowerShell scripts.",
        "",
    ]


def main(argv: List[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run: uv run python tools/coverage_matrix.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
