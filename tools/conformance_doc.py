#!/usr/bin/env python3
"""Generate ``docs/conformance.md`` from the conformance corpus.

The page lists every row the corpus replays, so the table cannot drift from the data CI runs
(``damage-control-dev corpus run``). The page is derived text; the pass/fail check is the corpus run.

    conformance_doc.py          # write docs/conformance.md
    conformance_doc.py --check  # exit 1 if it is stale
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import List

from damage_control import corpus

OUT = Path(__file__).resolve().parent.parent / "docs" / "conformance.md"


def cell(text: str) -> str:
    """A table-safe inline code span (the corpus holds ``|`` in pipelines)."""
    return "`" + text.replace("|", "\\|").replace("`", "'") + "`"


def render() -> str:
    data = corpus.load()
    rows = data["rows"]
    out: List[str] = [
        "# Conformance",
        "",
        "Respellings of the same operation must get the same verdict. The conformance corpus is a list of",
        "commands, each with the directory it runs in and the verdict Claude Code should act on, replayed through",
        "the real hook entrypoint as a subprocess. Every row below passes on the current code; CI fails if one stops.",
        "",
        "This page is generated by `tools/conformance_doc.py` from the corpus; do not edit it by hand.",
        "Regenerate with `python tools/conformance_doc.py`. Replay it yourself with `damage-control-dev corpus run`",
        "(`--json` for a machine-readable result).",
        "",
        "Verdicts are `block` (refused), `ask` (the user is asked) and `allow`. In a command, `@HOME@` is the home",
        "directory the hook sees and `@ROOT@` is a scratch directory holding the script files a row runs. A row whose",
        "source says *control* is the same spelling on a harmless command: it must stay allowed.",
        "",
        "| Class | Rows | What it covers |",
        "|---|---|---|",
    ]
    for name, description in data["classes"].items():
        out.append(f"| [{name}](#{name}) | {sum(r['class'] == name for r in rows)} | {description} |")
    out.append(f"| **Total** | {len(rows)} | |")
    for name, description in data["classes"].items():
        out += ["", f"## {name}", "", description, "", "| Command | Directory | Verdict | Source |", "|---|---|---|---|"]
        out += [f"| {cell(r['command'])} | {cell(r['cwd'])} | {r['verdict']} | {r['source']} |" for r in rows if r["class"] == name]
    out += [
        "",
        "## Known limits",
        "",
        "A table of passing rows is not a proof of coverage; what is not covered is listed in the",
        "[threat model](threat-model.md#what-it-does-not-protect-against). To add a spelling the rules do not yet",
        "judge, see [submitting a corpus row](../CONTRIBUTING.md#submitting-a-corpus-row).",
        "",
    ]
    return "\n".join(out)


def main(argv: List[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run: uv run python tools/conformance_doc.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
